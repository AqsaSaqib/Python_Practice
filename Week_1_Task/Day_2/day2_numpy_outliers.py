# Implementation
import numpy as np 
sensor_data = np.random.randint(2, 30, size = 12).reshape(3,4)
print("The Values of sensor data is as follow:\n", sensor_data)

# Statistics
mean = np.mean(sensor_data)
print("The mean of sensor_data is:\n", mean)

